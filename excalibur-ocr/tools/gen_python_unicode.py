"""The character table behind com.eonmux.excalibur.ocr.text.PythonText.

Indra's text rules use Python's str predicates and unicodedata.east_asian_width,
which follow the Unicode version of the Python that runs them (3.14: Unicode 16.0).
Java 21 knows Unicode 15.0 and has no equivalent of isspace, isdigit or the East
Asian width, so the port reads Python's answers from this table instead: one line
per predicate, its name and then the code point ranges where it holds, in hex.

Run with the Python environment Indra OCR is installed in:
    python tools/gen_python_unicode.py \
        src/main/resources/com/eonmux/excalibur/ocr/text/python-unicode.txt
"""
import sys
import unicodedata

PREDICATES = {
    "space": str.isspace,
    "alpha": str.isalpha,
    "lower": str.islower,
    "upper": str.isupper,
    "digit": str.isdigit,
    "decimal": str.isdecimal,
    "wide": lambda c: unicodedata.east_asian_width(c) in "WF",
}


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        hit = pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


with open(sys.argv[1], "w", encoding="ascii") as f:
    f.write(f"# Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}: "
            "code point ranges where each str predicate holds; generated by "
            "excalibur-ocr/tools/gen_python_unicode.py\n")
    for name, pred in PREDICATES.items():
        f.write(name + " " + " ".join(f"{a:X}-{b:X}" for a, b in ranges(pred)) + "\n")
